import SwiftUI
import Testing
@testable import UphillAI

@MainActor
struct OnboardingZonePreviewTests {
    @Test func heartRateMarkersUseEnteredRange() {
        let bar = TrainingZoneBar(aetHr: 145, antHr: 170, restingHr: 55, maxHr: 190)
        #expect(bar.hasHeartRateScale)
        #expect(abs(bar.boundaries[2] - 90.0 / 135) < 0.001)
        #expect(abs(bar.boundaries[3] - 115.0 / 135) < 0.001)
        #expect(bar.boundaries.first == 0 && bar.boundaries.last == 1)
        #expect(TrainingZoneBar(aetHr: 145).hasHeartRateScale == false)
        #expect(TrainingZoneBar(aetHr: 175, antHr: 160, restingHr: 55, maxHr: 190).hasHeartRateScale == false)
    }

    @Test func pacePreviewMatchesBackendFiveZoneReference() {
        var d = PlanSetupDraft(prefill: nil, today: .now, calendar: .current)
        #expect(OnboardingPacePreview.ranges(draft: d) == nil)
        d.aetHr = 145; d.antHr = 170
        d.zone2PaceMin = "6:40"; d.zone2PaceMax = "5:50"
        // Reference values generated by PlanGenerator.estimate_pace_zones.
        #expect(OnboardingPacePreview.ranges(draft: d) == ["7:41 - 6:40", "6:40 - 5:50", "5:50 - 5:14", "5:14 - 4:46", "4:46 - 4:14"])
        d.thresholdPace = "4:45"
        #expect(OnboardingPacePreview.ranges(draft: d) == ["6:39 - 5:56", "5:56 - 5:28", "5:28 - 4:59", "4:59 - 4:39", "4:39 - 4:11"])
        d.thresholdPace = "4:99"
        #expect(OnboardingPacePreview.ranges(draft: d) == nil)
    }
}
