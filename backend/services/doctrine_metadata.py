def get_scheduler_chunk_metadata(title: str | None) -> dict[str, Any] | None:
    """Return structured book provenance for a scheduler philosophy chunk title."""
    if not title:
        return None
    # Exact match
    if title in SCHEDULER_CHUNK_PROVENANCE:
        meta = dict(SCHEDULER_CHUNK_PROVENANCE[title])
        ch_str = f"Chapter {meta['chapter_num']}: {meta['chapter_title']}"
        meta["chapter"] = ch_str
        meta["citation_label"] = f"{meta['book']} — {ch_str}"
        return meta

    # Partial / case-insensitive match
    title_lower = title.strip().lower()
    for prov_title, meta_raw in SCHEDULER_CHUNK_PROVENANCE.items():
        if title_lower == prov_title.lower() or title_lower in prov_title.lower() or prov_title.lower() in title_lower:
            meta = dict(meta_raw)
            ch_str = f"Chapter {meta['chapter_num']}: {meta['chapter_title']}"
            meta["chapter"] = ch_str
            meta["citation_label"] = f"{meta['book']} — {ch_str}"
            return meta

    return None
